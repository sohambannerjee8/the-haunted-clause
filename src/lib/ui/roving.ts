// Roving-tabindex moves within one room (haunted-house-ui R9.3, PLAN_DECISIONS.md C1.8).
// Returns the new index, or null when the key is not a move.
export function nextIndex(key: string, index: number, count: number): number | null {
  if (count <= 0) return null;
  switch (key) {
    case "ArrowRight":
    case "ArrowDown":
      return (index + 1) % count;
    case "ArrowLeft":
    case "ArrowUp":
      return (index - 1 + count) % count;
    case "Home":
      return 0;
    case "End":
      return count - 1;
    default:
      return null;
  }
}
